// Regenerate with: npm run vendor:chokidar
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

export const VENDORED_CHOKIDAR_PATH = fileURLToPath(new URL("../server/vendor/chokidar.js", import.meta.url));

function packageFile(name: string, file: string): string {
  return fileURLToPath(new URL(`../node_modules/${name}/${file}`, import.meta.url));
}

async function licenseComment(name: string): Promise<string> {
  const license = await readFile(packageFile(name, "LICENSE"), "utf8");
  return `/*\n${name} license:\n\n${license.trim().replaceAll("*/", "* /")}\n*/`;
}

async function installedVersion(name: string): Promise<string> {
  const manifestPath = packageFile(name, "package.json");
  const manifest: unknown = JSON.parse(await readFile(manifestPath, "utf8"));
  if (typeof manifest !== "object" || manifest === null || !("version" in manifest) || typeof manifest.version !== "string")
    throw new Error(`${manifestPath} has no version`);
  return manifest.version;
}

export async function bundleChokidar(): Promise<string> {
  const banner = [
    `// Bundled from the npm releases chokidar ${await installedVersion("chokidar")} and readdirp ${await installedVersion("readdirp")}, both MIT.`,
    "// Generated by scripts/vendor-chokidar.ts; do not edit.",
    await licenseComment("chokidar"),
    await licenseComment("readdirp"),
  ].join("\n");
  const result = await build({
    stdin: { contents: 'export { watch } from "chokidar";', resolveDir: fileURLToPath(new URL("..", import.meta.url)) },
    bundle: true,
    platform: "node",
    format: "esm",
    legalComments: "inline",
    banner: { js: banner },
    write: false,
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await writeFile(VENDORED_CHOKIDAR_PATH, await bundleChokidar());
