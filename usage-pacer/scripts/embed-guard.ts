// Regenerate with: npm run embed:guard
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const GUARD_DIR = fileURLToPath(new URL("../guard/", import.meta.url));
export const GENERATED_GUARD_FILES_PATH = fileURLToPath(new URL("../server/guard-files.generated.ts", import.meta.url));

export async function generateGuardFiles(): Promise<string> {
  const names = (await readdir(GUARD_DIR)).filter((name) => !name.startsWith("test_") && name !== "__pycache__").sort();
  const entries = await Promise.all(
    names.map(async (name) => `  ${JSON.stringify(name)}: ${JSON.stringify(await readFile(GUARD_DIR + name, "utf8"))},`),
  );
  return [
    "// Generated by scripts/embed-guard.ts; do not edit.",
    "export const guardFiles: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(GENERATED_GUARD_FILES_PATH, await generateGuardFiles());
}
